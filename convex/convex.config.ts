import {defineApp} from "convex/server";
import {v} from "convex/values";
import auth from "@convex-dev/auth/convex.config";
import authEmail from "@convex-dev/auth/components/email/convex.config";
import authPassword from "@convex-dev/auth/components/password/convex.config";
import resend from "@convex-dev/resend/convex.config";
import authGoogle from "@convex-dev/auth/components/google/convex.config";
const app=defineApp({env:{AUTH_GOOGLE_CLIENT_ID:v.string(),AUTH_GOOGLE_CLIENT_SECRET:v.string()}});
app.use(auth,{name:"auth"});
app.use(authEmail,{name:"authEmail"});
app.use(authPassword,{name:"authPassword"});
app.use(resend,{name:"resend"});
app.use(authGoogle,{name:"authGoogle",httpPrefix:"/oauth/google",env:{CLIENT_ID:app.env.AUTH_GOOGLE_CLIENT_ID,CLIENT_SECRET:app.env.AUTH_GOOGLE_CLIENT_SECRET}});
export default app;
